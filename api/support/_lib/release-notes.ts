/**
 * Заметки о выпусках — для команды, не для разработчика.
 *
 * Каждый деплой с исправлениями получает запись здесь; крон
 * `cron/release-notes` замечает новую версию и сам рассылает её сейлзам:
 * в систему (колокольчик) и в Telegram через платформенного бота. Без этого
 * команда не понимала, решаются ли проблемы, о которых она говорила.
 *
 * Пишется языком пользователя: что было не так → что теперь → где смотреть.
 * Первая запись — самая свежая.
 */

export interface ReleaseItem {
  kind: 'fix' | 'new' | 'change'
  text: string
  /** Где это увидеть: страница или блок. */
  where?: string
}

export interface Release {
  /** Уникальная версия; по ней крон понимает, что появилось новое. */
  version: string
  /** Дата выпуска, Ташкент. */
  date: string
  title: string
  items: ReleaseItem[]
}

